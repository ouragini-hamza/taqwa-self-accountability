export interface QuranRef {
  surah: number; // 1..114
  ayah: number;
  ayahTo?: number;
}

export function validateQuranRef(ref: Partial<QuranRef> | undefined): string | null {
  if (!ref || !ref.surah || !ref.ayah) return "يجب إدخال السورة ورقم الآية.";
  if (!Number.isInteger(ref.surah) || ref.surah < 1 || ref.surah > 114) return "رقم السورة غير صحيح.";
  const max = AYAH_COUNTS[ref.surah - 1] ?? 0;
  if (!Number.isInteger(ref.ayah) || ref.ayah < 1 || ref.ayah > max)
    return `سورة ${SURAH_NAMES[ref.surah - 1]} عدد آياتها ${max}.`;
  if (ref.ayahTo !== undefined) {
    if (!Number.isInteger(ref.ayahTo) || ref.ayahTo < ref.ayah || ref.ayahTo > max)
      return "نهاية المقطع يجب أن تكون بعد آية البداية وضمن السورة.";
  }
  return null;
}

export function formatQuranRef(ref: QuranRef): string {
  const name = SURAH_NAMES[ref.surah - 1];
  return ref.ayahTo && ref.ayahTo !== ref.ayah
    ? `${name} ${ref.ayah}–${ref.ayahTo}`
    : `${name} ${ref.ayah}`;
}